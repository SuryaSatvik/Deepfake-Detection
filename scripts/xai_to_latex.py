"""
Turn results/xai/ into the LaTeX results block of the chapter's explanation
benchmark (Section "A benchmark for the explanations themselves").

    python scripts/xai_to_latex.py --chapter-dir path/to/chapter_deepfakes
    python scripts/xai_to_latex.py --pending --chapter-dir ...    # placeholder block

Writes <chapter-dir>/dfk_xai_bench_results.tex (the section \\input{}s it) and
copies two figures to <chapter-dir>/Figure/. Without --chapter-dir it writes to
results/xai/latex/.

No number in the output is typed by hand: every value comes from the CSV/JSON
files run_xai_eval.py wrote, and every sentence is a template whose wording is
chosen by the numbers (e.g. "beats random" only when the 95% CI excludes zero).
Read the generated sentences once before submitting — they are accurate, not
eloquent.

Refuses results from a --demo run (random weights) unless --allow-demo, and
then stamps DEMO on every caption.
"""
from __future__ import annotations

import argparse
import json
import math
import shutil
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUTNAME = "dfk_xai_bench_results.tex"
NAMES = {"gradcam": "Grad-CAM", "ig_blur": "IG (blur baseline)", "ig_mean": "IG (mean-face baseline)",
         "occlusion": "Patch occlusion", "kshap": "KernelSHAP", "centre": "Centre prior (control)",
         "kshap_reseed": "KernelSHAP (reseed)"}
TNAMES = {"gradcam": "Grad-CAM", "ig_blur": "IG, blur base", "ig_mean": "IG, mean face",
          "occlusion": "Occlusion", "kshap": "KernelSHAP", "centre": "Centre prior",
          "kshap_reseed": "KernelSHAP reseed"}
SHORT = {"gradcam": "Grad-CAM", "ig_blur": "IG (blur)", "ig_mean": "IG (mean face)",
         "occlusion": "occlusion", "kshap": "KernelSHAP", "centre": "the centre prior"}


# ---------------------------------------------------------------- formatting
def ok(v):
    return v is not None and not (isinstance(v, float) and math.isnan(v))


def f(v, d=3, sign=False):
    if not ok(v):
        return "---"
    s = f"{v:+.{d}f}" if sign else f"{v:.{d}f}"
    return s.replace("-", "$-$") if not sign else s.replace("+", "$+$").replace("-", "$-$")


def pv(p):
    return "$p<0.001$" if ok(p) and p < 0.001 else (f"$p={p:.3f}$" if ok(p) else "$p$ n/a")


def tex_safe(t):
    return (str(t).replace(">=", r"$\geq$").replace("<=", r"$\leq$").replace("—", "---")
            .replace("%", r"\%").replace("_", r"\_").replace(" -0", " $-$0"))


def pct(v, d=0):
    return "---" if not ok(v) else f"{100 * v:.{d}f}\\%"


def ci(s):
    """'[-0.0007, +0.0147]' -> '[$-$0.001, $+$0.015]'"""
    try:
        lo, hi = [float(x) for x in str(s).strip("[]").split(",")]
    except Exception:
        return ""
    return f"[{f(lo, 3, True)}, {f(hi, 3, True)}]"


def ci_lo(s):
    try:
        return float(str(s).strip("[]").split(",")[0])
    except Exception:
        return float("nan")


def listing(items):
    items = list(items)
    if not items:
        return ""
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def num_word(n):
    return ["no", "one", "two", "three", "four", "five", "six"][n] if 0 <= n <= 6 else str(n)


# ---------------------------------------------------------------- pending
def pending_block():
    return r"""% GENERATED by scripts/xai_to_latex.py --pending. Re-run the script after
% scripts/run_xai_eval.py has finished; this file is overwritten.
\begin{svgraybox}
\textbf{Results pending.} The benchmark above is implemented and its metric code
passes known-answer tests on models with planted answers, but it has not yet been
run on the trained checkpoints. This block is generated from the benchmark's output
files by \texttt{scripts/xai\_to\_latex.py}, so that no number in it is typed by
hand, and it will be replaced by the faithfulness, stability and arbitration tables
once the run is complete.
\end{svgraybox}
"""


# ---------------------------------------------------------------- results
def build(res: Path, demo_ok: bool):
    sp = json.load(open(res / "spatial_summary.json"))
    demo = bool(sp.get("args", {}).get("demo"))
    if demo and not demo_ok:
        sys.exit("results come from a --demo run (random weights). Refusing to write them into "
                 "the chapter. Pass --allow-demo only to test the LaTeX.")
    tag = r"\textbf{DEMO (random weights) --- not results.} " if demo else ""
    tab = pd.read_csv(res / "spatial_faithfulness.csv")
    stab = pd.read_csv(res / "stability.csv").set_index("method") if (res / "stability.csv").exists() else pd.DataFrame()
    san_path = res / "sanity.csv"
    san = (pd.read_csv(san_path, header=[0, 1], index_col=0)
           if san_path.exists() and san_path.stat().st_size > 10 else pd.DataFrame())
    arb = json.load(open(res / "arbitration_summary.json")) if (res / "arbitration_summary.json").exists() else None
    comp = pd.read_csv(res / "arbitration_comparison.csv") if arb else None

    a = sp["args"]; n = sp["n"]; model = a["model"]
    fills = [x for x in ("blur", "mean", "roll") if x in set(tab["fill"])]
    methods = [m for m in ("gradcam", "ig_blur", "ig_mean", "occlusion", "kshap", "centre") if m in set(tab["method"])]
    T = {(r.method, r.fill): r for r in tab.itertuples()}
    L = [f"% GENERATED by scripts/xai_to_latex.py from {res.as_posix()} ({sp['run_utc']}). Do not edit by hand.", ""]

    # ---- sample sentence
    smp = sp["sample"]
    errs = smp.get("real_error", {}).get("sampled", 0) + smp.get("fake_error", {}).get("sampled", 0)
    L += [r"\paragraph{Results.} " + tag +
          f"The spatial study used {n} test clips of {model}"
          + (" (the run was interrupted, so this is a partial sample)" if sp.get("partial") else "")
          + f", of which {errs} were errors of the model, over-sampled so that the correctness test has power; "
            "population means are weighted by inverse sampling probability. "
          + f"Each clip cost about {sp['forwards_per_clip']:.0f} forward passes.", ""]

    # ---- faithfulness table
    L += [r"\begin{table}[htbp]",
          r"\caption{" + tag + f"Spatial faithfulness of explanations of {model} ($n={n}$ test clips). "
          r"$\Delta$: deletion-AUC gain over the random ranking, paired per clip, with bootstrap 95\% interval "
          r"(positive means the explanation's cells remove evidence faster than random cells). "
          r"Bold: interval excludes zero. Insertion AUC, comprehensiveness and $|$sufficiency$|$ are under the blur fill. "
          r"Borda: points summed over the five metrics and the two primary fills.}",
          r"\label{tab:dfk_xaib_faith}", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{2pt}",
          r"\begin{tabular}{l" + "c" * len(fills) + "cccc}", r"\hline\noalign{\smallskip}",
          "Method & " + " & ".join(f"$\\Delta$ {x}" for x in fills) + r" & Ins. & Comp. & $|$Suff.$|$ & Borda \\",
          r"\noalign{\smallskip}\svhline\noalign{\smallskip}"]
    for m in methods:
        cells = []
        for x in fills:
            r = T[(m, x)]
            val = f(r.d_del_vs_random, 3, True)
            val = f"\\textbf{{{val}}}" if r.beats_random else val
            cells.append(val + (f" {ci(r.d_del_CI)}" if x != "roll" else ""))
        rb = T[(m, "blur")]
        borda = sum(T[(m, x)].borda for x in ("blur", "mean") if (m, x) in T)
        L.append(f"{TNAMES[m]} & " + " & ".join(cells) +
                 f" & {f(rb.ins_auc)} & {f(rb.comp_mean)} & {f(rb.suff_abs)} & {borda:.0f} \\\\")
    L += [r"\noalign{\smallskip}\hline\noalign{\smallskip}", r"\end{tabular}", r"\end{table}", ""]

    # ---- faithfulness sentences
    real = [m for m in methods if m != "centre"]
    beats = sp["beats_random"]
    both = [m for m in real if all(beats.get(m, {}).get(x) for x in ("blur", "mean"))]
    w = sp["winner"]
    S = []
    if both:
        S.append(f"Under both primary fills, {num_word(len(both))} of the {num_word(len(real))} methods "
                 f"beat the random ranking: {listing(SHORT[m] for m in both)}.")
        S.append(f"Ranked by Borda count, the benchmark's winner is \\textbf{{{SHORT[w]}}}.")
        cen = [T[(w, x)] for x in ("blur", "mean")]
        cen_ok = [ci_lo(c.d_del_CI) > 0 and c.p_centre < 0.05 and c.d_del_vs_centre > 0 for c in cen]
        S.append(f"Against the centre prior it gains {f(cen[0].d_del_vs_centre, 3, True)} (blur, {pv(cen[0].p_centre)}) "
                 f"and {f(cen[1].d_del_vs_centre, 3, True)} (mean face, {pv(cen[1].p_centre)})"
                 + (", so its maps say something specific to each clip." if all(c.p_centre < 0.05 and c.d_del_vs_centre > 0 for c in cen)
                    else ", so on at least one fill its ranking is not distinguishable from \\emph{the middle of the face}."))
    else:
        S.append(f"No method beat the random ranking under both primary fills. By the rule set in advance, "
                 f"no spatial explanation of {model} should therefore be shown to a user.")
    one = [m for m in real if m not in both and any(beats.get(m, {}).get(x) for x in ("blur", "mean"))]
    if one:
        lst = listing(SHORT[m] for m in one)
        S.append(f"{lst[0].upper() + lst[1:]} "
                 f"beat{'s' if len(one) == 1 else ''} random under one primary fill only, which is exactly the "
                 "case the two-fill rule exists to catch.")
    tau = sp.get("fill_rank_agreement_kendall_tau", {})
    if ok(tau.get("blur~mean")):
        S.append(f"The two primary fills order the methods with Kendall $\\tau={tau['blur~mean']:.2f}$.")
    c = sp["controls"]
    if "roll" in fills:
        nroll = sum(1 for m in real if beats.get(m, {}).get("roll"))
        d_roll = c["p_target_unperturbed"] - c["p_target_all_filled_roll"]
        S.append(f"Under CFX's roll fill {num_word(nroll)} method{'s' if nroll != 1 else ''} beat{'' if nroll != 1 else 's'} random, "
                 f"and replacing \\emph{{every}} cell moves $p$ by only {f(d_roll, 3)}, against "
                 f"{f(c['p_target_unperturbed'] - c['p_target_all_filled_blur'], 3)} for blur and "
                 f"{f(c['p_target_unperturbed'] - c['p_target_all_filled_mean'], 3)} for the mean face"
                 + (": on aligned crops that fill removes almost nothing, and faithfulness numbers computed with it "
                    "should not be read as evidence either way." if abs(d_roll) < 0.05 else "."))
    g = sp["modality_gate"]
    S.append(f"Two limits frame all of these numbers. The spatial branch carries {pct(g['mean_spatial_share'])} of "
             f"{model}'s decision on these clips by exact Shapley, and pixels can reach at most "
             f"{pct(g['mean_pixel_reachable_share'])} of it, because LMF reads landmark motion rather than pixels.")
    dg = sp.get("degenerate_map_rate", {})
    bad = {m: v for m, v in dg.items() if v and v > 0}
    if bad:
        S.append("Some maps were constant, so rank nothing: " +
                 listing(f"{SHORT[m]} on {pct(v)} of clips" for m, v in bad.items()) + ".")
    igr = sp.get("ig_completeness_residual_median", {})
    if igr:
        worst = max(igr.values())
        S.append(f"The median IG completeness residual is {f(igr.get('ig_blur_resid'), 2)} (blur baseline) and "
                 f"{f(igr.get('ig_mean_resid'), 2)} (mean face)"
                 + (", so the path integral is well resolved." if worst < 0.1 else
                    "; above $0.1$ the attributions do not add up to the output change they claim to explain, "
                    "and the IG rows should be read with that caveat."))
    L += [" ".join(S), ""]

    # ---- stability + sanity table
    if len(stab):
        L += [r"\begin{table}[htbp]",
              r"\caption{" + tag + r"Stability and sanity of the spatial explanations. $\rho$: Spearman correlation of "
              r"the unit scores; $J$: overlap of the top 10\% of cells; noise: $\sigma=0.01$ pixel noise; frames: a "
              r"different set of 16 frames from the same clip. Randomised: correlation with the map of a model whose "
              r"classifier head (and, second value, also the last EfficientNet block) was re-initialised --- values "
              r"near zero pass. Constant: share of clips whose map was constant.}",
              r"\label{tab:dfk_xaib_stab}", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
              r"\begin{tabular}{lcccccc}", r"\hline\noalign{\smallskip}",
              r"Method & $\rho$ noise & $J$ noise & $\rho$ frames & $J$ frames & Randomised & Constant \\",
              r"\noalign{\smallskip}\svhline\noalign{\smallskip}"]
        sancol = {"gradcam": "rho_gradcam", "ig_blur": "rho_ig_blur"}
        for m in [x for x in ("gradcam", "ig_blur", "ig_mean", "occlusion", "kshap", "kshap_reseed") if x in stab.index]:
            r = stab.loc[m]
            rs = "---"
            if m in sancol and len(san):
                try:
                    v1 = san.loc["head", (sancol[m], "mean")]; v2 = san.loc["head+block", (sancol[m], "mean")]
                    rs = f"{f(v1, 2)} / {f(v2, 2)}"
                except KeyError:
                    pass
            L.append(f"{TNAMES[m]} & {f(r.get('rho_noise'), 2)} & {f(r.get('jac_noise'), 2)} & "
                     f"{f(r.get('rho_frames'), 2)} & {f(r.get('jac_frames'), 2)} & {rs} & "
                     f"{pct(dg.get(m)) if m in dg else '---'} \\\\")
        L += [r"\noalign{\smallskip}\hline\noalign{\smallskip}", r"\end{tabular}", r"\end{table}", ""]
        S = []
        rf = {m: stab.loc[m].get("rho_frames") for m in real if m in stab.index and ok(stab.loc[m].get("rho_frames"))}
        if rf:
            hi_m, lo_m = max(rf, key=rf.get), min(rf, key=rf.get)
            S.append(f"Across a different set of frames from the same clip, {SHORT[hi_m]} is the most stable "
                     f"($\\rho={rf[hi_m]:.2f}$) and {SHORT[lo_m]} the least ($\\rho={rf[lo_m]:.2f}$).")
        if "kshap_reseed" in stab.index and ok(stab.loc["kshap_reseed"].get("rho_noise")):
            v = stab.loc["kshap_reseed"]["rho_noise"]
            S.append(f"Re-running KernelSHAP with a different random seed on the same clip gives $\\rho={v:.2f}$"
                     + (", so its sampling error is small at 512 coalitions." if v >= 0.8 else
                        ", so part of what its map shows is sampling noise from the 512 coalitions."))
        if len(san):
            for m, col in sancol.items():
                try:
                    v = san.loc["head+block", (col, "mean")]
                except KeyError:
                    continue
                if ok(v):
                    S.append(f"After randomising the head and last block, {SHORT[m]}'s map keeps $\\rho={v:.2f}$ with the original"
                             + (" --- it passes the sanity check." if abs(v) < 0.3 else
                                " --- more than a map that depends on the learned weights should, so part of it reflects the input image rather than the model." ))
        L += [" ".join(S), ""]

    # ---- counterfactuals, temporal, correctness
    cf, tp, fc = sp["counterfactuals"], sp["temporal"], sp.get("faithfulness_vs_correctness", {})
    S = []
    parts = []
    if ok(cf.get("spectral_median_cutoff_nyq_pred_fake")):
        parts.append(f"${cf['spectral_median_cutoff_nyq_pred_fake']:.2f}$ for clips called fake")
    if ok(cf.get("spectral_median_cutoff_nyq_pred_real")):
        parts.append(f"${cf['spectral_median_cutoff_nyq_pred_real']:.2f}$ for clips called real")
    S.append(f"Low-pass filtering flips the verdict on {pct(cf['spectral_flip_rate'])} of clips"
             + (f"; the median cutoff at which it flips, as a fraction of the Nyquist frequency, is {listing(parts)}."
                if parts else "."))
    S.append(f"Freezing frames in occlusion order flips {pct(cf['temporal_flip_rate'])} of verdicts"
             + (f", after a median of {cf['temporal_median_frames_to_flip']:.0f} frame{'' if cf['temporal_median_frames_to_flip'] == 1 else 's'}."
                if ok(cf.get("temporal_median_frames_to_flip")) else "."))
    ks = tp["k_frames_frozen"]
    if ks:
        k = ks[-1]
        S.append(f"For {model}, freezing the {k} frames that occlusion ranks highest removes {f(tp['occlusion'][-1], 2)} logit units "
                 f"of margin, against {f(tp['attention'][-1], 2)} for the attention ranking and {f(tp['random'][-1], 2)} for random "
                 f"frames (mean Spearman correlation of attention with occlusion {f(tp['rho_attention_occlusion_mean'], 2)}).")
    if fc.get("delta_auc_added_by_faithfulness") is not None:
        lo, hi = fc["delta_CI"]
        S.append(f"Finally, does a faithful explanation mark a correct verdict? On the {fc['n']} clips ({fc['n_errors']} errors), "
                 f"the per-clip gain of {SHORT[w]} over random predicts correctness with AUROC {fc['auroc_faithfulness']:.2f} "
                 f"[{fc['auroc_faithfulness_CI'][0]:.2f}, {fc['auroc_faithfulness_CI'][1]:.2f}], against {fc['auroc_confidence']:.2f} "
                 f"for calibrated confidence alone. Adding it to confidence changes the cross-validated AUROC by "
                 f"{f(fc['delta_auc_added_by_faithfulness'], 3, True)} [{f(lo, 3, True)}, {f(hi, 3, True)}]"
                 + (": faithfulness carries information about correctness that confidence does not." if lo > 0 else
                    ": there is no evidence that it adds anything, so faithfulness should be reported as a property of the "
                    "explanation, not used as a second confidence score."))
    elif fc.get("note"):
        S.append(f"The correctness test could not be run: {tex_safe(fc['note'])}.")
    L += [" ".join(S), ""]

    # ---- arbitration
    if arb:
        L += [r"\begin{table}[htbp]",
              r"\caption{" + tag + f"Calibrated single models and the two stacks on the test split ($n={arb['n_test']}$); "
              r"everything is fitted on validation only. $\Delta$ columns compare with the best single model chosen on "
              r"validation (" + arb["best_single_by_val"] + r"), with paired-bootstrap 95\% intervals. "
              r"Bold rows meet the pre-set rule for shipping a stack.}",
              r"\label{tab:dfk_xaib_arb}", r"\centering", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
              r"\begin{tabular}{lccccc}", r"\hline\noalign{\smallskip}",
              r"Model & AUC [95\% CI] & Brier & NLL & $\Delta$AUC & $\Delta$Brier \\",
              r"\noalign{\smallskip}\svhline\noalign{\smallskip}"]
        for r in comp.itertuples():
            d = r._asdict()
            name = str(d["model"]).replace("stack: ", "Stack: ").replace("(Platt)", "(Platt)")
            da = d.get("dAUC_vs_best"); db = d.get("dBrier_vs_best")
            row = (f"{name} & {f(d['test_AUC'])} {ci(d['AUC_CI'])} & {f(d['Brier'])} & {f(d['NLL'])} & "
                   + (f"{f(da, 3, True)} {ci(d.get('dAUC_CI_vs_best'))}" if ok(da) else "---") + " & "
                   + (f"{f(db, 4, True)}" if ok(db) else "---") + r" \\")
            if d.get("resolved_better_than_best") is True:
                row = r"\textbf{" + row.replace(r" \\", "") + r"} \\"
            L.append(row)
        L += [r"\noalign{\smallskip}\hline\noalign{\smallskip}", r"\end{tabular}", r"\end{table}", ""]
        wbm = arb["stack_weight_share_by_model"]
        S = [f"The stack over branch Shapley values puts " + listing(f"{pct(v)} of its weight on {k}" for k, v in wbm.items()) + ".",
             f"The prediction written into the CFX design before any run, that most weight would go to "
             f"{arb['preregistered_routing_prediction']}, \\textbf{{{'held' if arb['routing_prediction_held'] else 'did not hold'}}}"
             + ("." if arb["routing_prediction_held"] else f": most weight went to {arb['stack_routes_most_weight_to']}."),
             "Decision by the pre-set rule: " + tex_safe(arb["decision"]).replace("dAUC", r"$\Delta$AUC")
             .replace("dBrier", r"$\Delta$Brier") + "."]
        L += [" ".join(S), ""]

    # ---- figure
    L += [r"\begin{figure}[htbp]", r"\centering",
          r"\includegraphics[width=0.92\linewidth]{Figure/dfk_xaib_gain.png}", ""]
    if arb:
        L += [r"\includegraphics[width=0.92\linewidth]{Figure/dfk_xaib_reliability.png}"]
    L += [r"\caption{" + tag + f"(a) Deletion-AUC gain over random for each explanation of {model}, with 95\\% intervals, "
          r"under the blur ($\bullet$), mean-face ($\square$) and roll ($\triangle$) fills."
          + (r" (b) Reliability matrix of the four-model panel on validation: mean share of $|\phi|$ per branch, and "
             r"how well each branch's Shapley value alone separates real from fake (AUC)." if arb else "") + "}",
          r"\label{fig:dfk_xaib}", r"\end{figure}", ""]
    return "\n".join(L), demo


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", default=str(ROOT / "results" / "xai"))
    ap.add_argument("--chapter-dir", default=None)
    ap.add_argument("--pending", action="store_true")
    ap.add_argument("--allow-demo", action="store_true")
    a = ap.parse_args()
    res = Path(a.results)
    out = Path(a.chapter_dir) if a.chapter_dir else res / "latex"
    (out / "Figure").mkdir(parents=True, exist_ok=True)
    if a.pending or not (res / "spatial_summary.json").exists():
        if not a.pending:
            print(f"no {res / 'spatial_summary.json'} — writing the pending block")
        (out / OUTNAME).write_text(pending_block(), encoding="utf-8")
        print(f"wrote {out / OUTNAME} (pending)"); return
    tex, demo = build(res, a.allow_demo)
    (out / OUTNAME).write_text(tex, encoding="utf-8")
    for src, dst in (("fig_gain_vs_random.png", "dfk_xaib_gain.png"),
                     ("fig_reliability_matrix.png", "dfk_xaib_reliability.png")):
        p = res / "figures" / src
        if p.exists():
            shutil.copy(p, out / "Figure" / dst)
    print(f"wrote {out / OUTNAME} and figures{' (DEMO — do not submit)' if demo else ''}")


if __name__ == "__main__":
    main()
